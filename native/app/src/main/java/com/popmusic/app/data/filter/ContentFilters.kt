package com.popmusic.app.data.filter

import com.popmusic.app.domain.Song

/**
 * Filtros de contenido al estilo de Echo ("Ocultar videos", "Ocultar Shorts").
 * Heurísticas sobre duración y título para limpiar búsquedas, charts y feeds
 * sin tocar la biblioteca del usuario.
 */
object ContentFilters {

    /** Un "Short" dura 60-70 s como máximo. */
    private const val SHORTS_MAX_SECONDS = 70

    private val videoMarkers = listOf(
        "video oficial",
        "official video",
        "official music video",
        "videoclip",
        "music video",
        "lyric video",
        "video lyrics",
        "visualizer",
        "behind the scenes",
        "making of",
    )

    /**
     * Marcadores de contenido NO musical para el chart de tendencias:
     * el kiosk "trending_music" de YouTube a veces mete canciones de IA,
     * vídeos infantiles u otros ruidos que no son música de verdad.
     * Se comparan sobre " título artista " en minúsculas.
     */
    private val nonMusicMarkers = listOf(
        // Generadas por IA / plataformas de IA
        " ai ", " ia ", "ai song", "ai music", "ai-generated", "ai generated",
        "generated by ai", "canción de ia", "canciones de ia", "ia cover",
        "suno", "udio", "stablediffusion",
        // Infantil / de niños
        "kids", "niños", "niñas", "infantil", "infantiles", "para niños",
        "nursery", "rhymes", "cartoon", "canticuentos", "corralito",
        "payasos", "plim plim", "dora", "peppa", "coco melon", "blippi",
        // No música: vídeo, juego, charla
        "gameplay", "walkthrough", "trailer", "reaction", "reacción",
        "vlog", "podcast", "interview", "entrevista", "noticias",
        "audiolibro", "audiobook", "resumen", "tutorial", "unboxing",
        "highlights", "compilación", "compilation",
    )

    /** true si el título+artista parecen música de verdad (no IA/niños/vídeos). */
    fun isMusicOnly(song: Song): Boolean {
        val haystack = " ${song.title} ${song.artist} ".lowercase()
        return nonMusicMarkers.none { haystack.contains(it) }
    }

    /** Filtra un chart/tendencia a contenido puramente musical. */
    fun musicOnly(songs: List<Song>): List<Song> = songs.filter { isMusicOnly(it) }

    fun shouldHide(song: Song, hideVideos: Boolean, hideShorts: Boolean): Boolean {
        if (hideShorts && song.durationSeconds in 1..SHORTS_MAX_SECONDS) return true
        if (hideVideos) {
            val title = song.title.lowercase()
            if (videoMarkers.any { title.contains(it) }) return true
        }
        return false
    }

    fun apply(songs: List<Song>, hideVideos: Boolean, hideShorts: Boolean): List<Song> {
        if (!hideVideos && !hideShorts) return songs
        return songs.filterNot { shouldHide(it, hideVideos, hideShorts) }
    }
}
